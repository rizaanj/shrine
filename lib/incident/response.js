function generateRevokeSteps(findings) {
  const typeSteps = {
    'API Key': [
      'Revoke key in dashboard',
      'Notify affected users',
      'Audit access logs for abuse'
    ],
    'Database Exposed': [
      'Restrict RLS immediately',
      'Audit data access logs',
      'Notify affected users'
    ],
    'IDOR': [
      'Fix RLS policies',
      'Audit cross-user access attempts',
      'Notify if data leaked'
    ],
    'RLS Disabled': [
      'Enable Row Level Security',
      'Create restrictive policies',
      'Audit data access logs'
    ],
    'JWT Secret Exposed': [
      'Rotate JWT secret immediately',
      'Invalidate all active sessions',
      'Audit token usage logs'
    ],
    'AWS Secret Key': [
      'Rotate AWS access key',
      'Review IAM permissions',
      'Audit CloudTrail logs'
    ],
    'GitHub Token': [
      'Revoke GitHub token',
      'Review repository access',
      'Audit commit history'
    ],
    'Database Credentials': [
      'Rotate database password',
      'Audit database connections',
      'Review access logs'
    ],
    'API Missing Auth': [
      'Add authentication middleware',
      'Audit unauthenticated access',
      'Review endpoint permissions'
    ],
    'XSS': [
      'Sanitize user input',
      'Implement CSP headers',
      'Audit affected endpoints'
    ],
    'Injection': [
      'Use parameterized queries',
      'Audit vulnerable endpoints',
      'Review input validation'
    ]
  };

  const stepsSet = new Set();
  for (const finding of findings) {
    if (finding.severity === 'critical' || finding.severity === 'high') {
      const steps = typeSteps[finding.type];
      if (steps) {
        for (const step of steps) {
          stepsSet.add(step);
        }
      }
    }
  }
  return Array.from(stepsSet);
}

function assessUserImpact(findings, options = {}) {
  const { filesScanned, tables } = options;
  
  let severity = 'low';
  if (findings.some(f => f.severity === 'critical') || findings.length > 10) {
    severity = 'critical';
  } else if (findings.some(f => f.severity === 'high') || findings.length > 5) {
    severity = 'high';
  } else if (findings.length > 0) {
    severity = 'medium';
  }

  let affectedUsers = 'unknown';
  const hasRLSDisabled = findings.some(f => f.type === 'RLS Disabled' || (f.table && f.severity === 'critical'));
  const hasIDORCritical = findings.some(f => f.type === 'IDOR' && f.severity === 'critical');
  const hasAnonAccess = findings.some(f => f.type === 'API Missing Auth' || (f.type === 'API Key' && f.severity === 'high'));

  if (hasRLSDisabled || hasIDORCritical) {
    affectedUsers = 'all';
  } else if (hasAnonAccess) {
    affectedUsers = 'some';
  }

  const dataExposedSet = new Set();
  for (const finding of findings) {
    if (finding.table) {
      dataExposedSet.add(finding.table);
    } else if (finding.file) {
      dataExposedSet.add(finding.file);
    }
  }
  const dataExposed = Array.from(dataExposedSet).slice(0, 10);

  const summary = `${findings.length} security issues detected. Severity: ${severity}. Potential data exposure in ${dataExposed.length} locations.`;

  return {
    severity,
    affectedUsers,
    dataExposed,
    summary
  };
}

function generateBreachNotice(impact, options = {}) {
  const { companyName = '[Company Name]' } = options;
  const date = new Date().toISOString().split('T')[0];
  const sanitizedCompany = companyName.toLowerCase().replace(/\s/g, '');

  return `# Security Incident Notice

Date: ${date}

## Summary
${impact.summary}

## Affected Users
${impact.affectedUsers === 'all' ? 'All users may be affected' : 'Some users may be affected'}.

## Actions Taken
- Security scan completed
- Issues identified and prioritized
- Remediation in progress

## Recommended User Actions
- Change passwords immediately
- Review account activity
- Enable 2FA if not already enabled

## Contact
For questions, contact security@${sanitizedCompany}.com

---
*This notice was generated by Shrine Security Scanner*`;
}

